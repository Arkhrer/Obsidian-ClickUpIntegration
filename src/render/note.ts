import { moment } from 'obsidian';
import { ClickUpTask } from '../clickup/types';

function statusOrder(group: ClickUpTask[]): number {
	return group[0]?.status.orderindex ?? Infinity;
}

function renderTask(task: ClickUpTask): string {
	const parts: string[] = [`[${task.name}](${task.url})`];
	if (task.priority?.priority) { parts.push(task.priority.priority); }
	if (task.due_date) { parts.push(`due ${moment(Number(task.due_date)).format('YYYY-MM-DD')}`); }
	return `- ${parts.join(' · ')}`;
}

export function renderNote(tasks: ClickUpTask[]): string {
	const lines: string[] = [];

	// 1. Frontmatter + callout
	lines.push(
		'---',
		'type: panel',
		'origin: clickup',
		`updated: ${moment().format('YYYY-MM-DDTHH:mm')}`,
		'tags:',
		'  - clickup',
		'---',
		'> [!info] Generated by ClickUp Integration. Do not edit: this note is rewritten on every update.',
		'',
	);

	// 2. Group tasks by status
	const groups = new Map<string, ClickUpTask[]>();
	for (const task of tasks) {
		const key = task.status.status;
		const group = groups.get(key) ?? [];
		group.push(task);
		groups.set(key, group);
	}

	// 3. One section per group
	const sorted = [...groups].sort(([, a], [, b]) => {
		const x = statusOrder(a);
		const y = statusOrder(b);
		return x === y ? 0: x < y ? -1 : 1;
	});
	for (const [status, group] of sorted) {
		lines.push(`## ${status} (${group.length})`);
		lines.push(...group.map(renderTask));
		lines.push('');
	}

	return lines.join('\n');
}
